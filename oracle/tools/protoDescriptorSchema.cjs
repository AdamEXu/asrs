// Prints the Rust table asrs_log::log::proto_decoder decodes descriptors with.
// usage: node protoDescriptorSchema.cjs <protobufjs package dir>
const P = process.argv[2];
const descriptor = require(P + "/ext/descriptor");
const protobuf = require(P + "/light");
const types = [];
function walk(ns) {
  for (const n of ns.nestedArray) {
    if (n instanceof protobuf.Type) types.push(n);
    if (n instanceof protobuf.Namespace) walk(n);
  }
}
walk(descriptor);
const out = [];
out.push("// Generated by `cargo xtask tables proto-descriptor` from protobufjs ext/descriptor, the");
out.push("// schema FileDescriptorProto is decoded with. Fields are in fieldsArray order. Do not edit.");
out.push("");
out.push("use super::descriptor::{SchemaDefault as D, SchemaField as F, SchemaKind as K};");
out.push("");
for (const t of types) t.setup();
out.push(`pub(super) const TYPES: [&[F]; ${types.length}] = [`);
for (const t of types) {
  out.push(`    // ${t.fullName}`);
  out.push("    &[");
  for (const f of t.fieldsArray) {
    f.resolve();
    let kind;
    if (f.resolvedType instanceof protobuf.Type) kind = `K::Message(${types.indexOf(f.resolvedType)})`;
    else if (f.resolvedType instanceof protobuf.Enum) kind = `K::Enum`;
    else kind = `K::Basic(${JSON.stringify(f.type)})`;
    let def;
    const td = f.typeDefault;
    if (f.repeated || f.resolvedType instanceof protobuf.Type) def = "D::None";
    else if (typeof td === "number") def = `D::Number(${td}.0)`;
    else if (typeof td === "boolean") def = `D::Bool(${td})`;
    else if (typeof td === "string") def = `D::Str(${JSON.stringify(td)})`;
    else if (f.long) def = "D::Long";
    else if (f.bytes) def = "D::Bytes";
    else throw new Error("default " + f.fullName);
    if (f.map) throw new Error("map in descriptor schema");
    if (f.partOf) throw new Error("oneof in descriptor schema");
    out.push(`        F { name: ${JSON.stringify(f.name)}, id: ${f.id}, kind: ${kind}, repeated: ${f.repeated}, required: ${f.required}, default: ${def} },`);
  }
  out.push("    ],");
}
out.push("];");
out.push("");
out.push(`pub(super) const FILE_DESCRIPTOR_PROTO: usize = ${types.indexOf(descriptor.FileDescriptorProto)};`);
console.log(out.join("\n"));
