// Prints crates/asrs-model/src/mathjs/sigs.rs: the dispatch-ordered signature table
// (`fn._typedFunctionData.signatures`) typed-function builds for each function asrs_model::mathjs
// ports, read from the real mathjs instance.
// usage: node mathjsSignatures.cjs <mathjs package dir>
const { create, all } = require(process.argv[2]);

const OPERATOR_FUNCTIONS = [
  "add", "subtract", "multiply", "divide", "pow", "mod", "unaryMinus", "unaryPlus", "factorial",
  "ctranspose", "bitAnd", "bitOr", "bitXor", "bitNot", "leftShift", "rightArithShift",
  "rightLogShift", "and", "or", "xor", "not", "equal", "unequal", "smaller", "larger",
  "smallerEq", "largerEq", "dotMultiply", "dotDivide", "dotPow"
];
const NAMED_FUNCTIONS = [
  "abs", "sqrt", "cbrt", "exp", "log", "log10", "log2", "round", "floor", "ceil", "fix", "sign",
  "min", "max", "sin", "cos", "tan", "asin", "acos", "atan", "atan2", "number", "square", "cube",
  "gamma"
];
const HELPER_FUNCTIONS = ["addScalar", "multiplyScalar", "equalScalar", "conj"];

const math = create(all);

// typed-function keeps a conversion in its target type's conversionsTo list, not on the
// conversion, and a signature it expands for a conversion keeps only the source type.
const targets = new Map();
const TYPE_NAMES = ["number", "Complex", "BigNumber", "Fraction", "Unit", "identifier", "string", "Chain", "Array", "Matrix", "DenseMatrix", "SparseMatrix", "Range", "Index", "boolean", "ResultSet", "Help", "function", "Date", "RegExp", "null", "undefined", "Object"];
for (const name of TYPE_NAMES) for (const c of math.typed._findType(name).conversionsTo) targets.set(c.index, name);

const constName = (fn) => fn.replace(/[A-Z]/g, (m) => "_" + m).toUpperCase();
const paramType = (t) => {
  if (!t.conversion) return `t(${JSON.stringify(t.name)})`;
  const to = targets.get(t.conversion.index);
  if (to === undefined) throw new Error(`no target for the conversion from ${t.name}`);
  return `c(${JSON.stringify(t.conversion.from)}, ${JSON.stringify(to)})`;
};
const param = (p) => `${p.restParam ? "r" : "p"}(&[${p.types.map(paramType).join(", ")}])`;

const out = [];
out.push("// Generated by `cargo xtask tables mathjs-signatures` from mathjs 11.3.0's typed functions");
out.push("// (`fn._typedFunctionData.signatures`, in dispatch order). Do not edit.");
out.push("");
out.push("use super::{Param, ParamType, Signature};");
out.push("");
out.push("const fn t(name: &'static str) -> ParamType {\n    ParamType { name, conversion: None }\n}");
out.push("");
out.push("const fn c(from: &'static str, to: &'static str) -> ParamType {\n    ParamType { name: from, conversion: Some((from, to)) }\n}");
out.push("");
out.push("const fn p(types: &'static [ParamType]) -> Param {\n    Param { types, rest: false }\n}");
out.push("");
out.push("const fn r(types: &'static [ParamType]) -> Param {\n    Param { types, rest: true }\n}");
out.push("");
out.push("const fn s(params: &'static [Param]) -> Signature {\n    Signature { params }\n}");
const fns = [...OPERATOR_FUNCTIONS, ...NAMED_FUNCTIONS, ...HELPER_FUNCTIONS];
for (const fn of fns) {
  const data = math[fn]._typedFunctionData;
  if (data === undefined) throw new Error(`${fn} is not a typed function`);
  out.push("");
  out.push(`static ${constName(fn)}: &[Signature] = &[`);
  for (const s of data.signatures) out.push(`    s(&[${s.params.map(param).join(", ")}]),`);
  out.push("];");
}
out.push("");
out.push("pub fn lookup(name: &str) -> Option<(&'static str, &'static [Signature])> {");
out.push("    Some(match name {");
for (const fn of fns) out.push(`        ${JSON.stringify(fn)} => (${JSON.stringify(math[fn].name)}, ${constName(fn)}),`);
out.push("        _ => return None,");
out.push("    })");
out.push("}");
process.stdout.write(out.join("\n") + "\n");
