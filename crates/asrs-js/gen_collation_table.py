#!/usr/bin/env python3
"""Regenerates src/collation/tables.rs from the js/collation-unsafe vector.

Usage:
  python3 crates/asrs-js/gen_collation_table.py \
      parity/vectors/js/collation-unsafe.jsonl.zst \
      crates/asrs-js/src/collation/tables.rs
"""

import json
import subprocess
import sys

HEADER = """// Generated by crates/asrs-js/gen_collation_table.py from the js/collation-unsafe parity
// vector, which the oracle entry `genCollationUnsafe` probes out of Electron's ICU 74.2.
"""


def read_text(path):
    if path.endswith(".zst"):
        return subprocess.run(
            ["zstd", "-d", "-q", "-c", path], check=True, capture_output=True, text=True
        ).stdout
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def table(name, ranges):
    rows = "".join(f"    (0x{lo:04x}, 0x{hi:04x}),\n" for lo, hi in ranges)
    return f"pub(crate) static {name}: &[(u16, u16)] = &[\n{rows}];\n"


def main():
    src, dst = sys.argv[1], sys.argv[2]
    records = {}
    for line in read_text(src).splitlines():
        if line.strip():
            records.update(json.loads(line))
    out = HEADER + "\n" + table("DIGITS", records["digits"]) + "\n" + table("UNSAFE_BACKWARD", records["unsafe"])
    with open(dst, "w", encoding="utf-8") as f:
        f.write(out)


if __name__ == "__main__":
    main()
