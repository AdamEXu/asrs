#!/usr/bin/env python3
"""Regenerates src/string/case_table.rs from the jstring/case-data vector.

Usage:
  python3 crates/asrs-js/gen_case_table.py \
      parity/vectors/jstring/case-data.jsonl.zst \
      crates/asrs-js/src/string/case_table.rs

Reads .jsonl, .jsonl.zst (via the `zstd` CLI), or stdin JSONL ("-" or no path).
"""

import json
import subprocess
import sys

HEADER = """// Generated by crates/asrs-js/gen_case_table.py from the jstring/case-data
// parity vector, which is emitted by the oracle entry `genCaseData` (Electron's
// V8 + ICU 74.2). Only code points with a non-identity mapping are listed;
// the final-sigma context rule is applied in code, not here.
"""


def read_text(path):
    if path is None or path == "-":
        return sys.stdin.read()
    if path.endswith(".zst"):
        return subprocess.run(
            ["zstd", "-d", "-q", "-c", path], check=True, capture_output=True, text=True
        ).stdout
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def units(s):
    raw = s.encode("utf-16-be", "surrogatepass")
    return [int.from_bytes(raw[i : i + 2], "big") for i in range(0, len(raw), 2)]


def fmt_map(entries):
    rows = []
    for cp, mapped in entries:
        us = ", ".join(str(u) for u in mapped)
        rows.append(f"    ({cp}, &[{us}]),")
    return "\n".join(rows)


def fmt_ranges(ranges):
    return ", ".join(f"({lo}, {hi})" for lo, hi in ranges)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    dst = sys.argv[2] if len(sys.argv) > 2 else "-"
    lower = []
    upper = []
    cased = []
    ignorable = []
    for line in read_text(src).splitlines():
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        if "cp" in rec:
            cp = rec["cp"]
            if "l" in rec and rec["l"] != chr(cp):
                lower.append((cp, units(rec["l"])))
            if "u" in rec and rec["u"] != chr(cp):
                upper.append((cp, units(rec["u"])))
        elif "cased" in rec:
            cased = rec["cased"]
        elif "caseIgnorable" in rec:
            ignorable = rec["caseIgnorable"]
    if not (lower and upper and cased and ignorable):
        raise SystemExit("input is missing case data or property ranges")
    lower.sort()
    upper.sort()
    text = HEADER + "\n"
    text += f"pub(crate) static LOWER: &[(u32, &[u16])] = &[\n{fmt_map(lower)}\n];\n\n"
    text += f"pub(crate) static UPPER: &[(u32, &[u16])] = &[\n{fmt_map(upper)}\n];\n\n"
    text += f"pub(crate) static CASED: &[(u32, u32)] = &[{fmt_ranges(cased)}];\n\n"
    text += (
        f"pub(crate) static CASE_IGNORABLE: &[(u32, u32)] = &[{fmt_ranges(ignorable)}];\n"
    )
    if dst == "-":
        sys.stdout.write(text)
    else:
        with open(dst, "w", encoding="utf-8") as f:
            f.write(text)


if __name__ == "__main__":
    main()
