//! Table generators: parse upstream TypeScript data literals and emit Rust
//! tables, so conversion factors and names are transcribed (not retyped).
//!
//! `cargo xtask tables units` rewrites `crates/asrs-log/src/units/tables.rs`
//! from `reference/AdvantageScope/src/shared/units.ts`. `--check` compares
//! without writing.

use std::fs;
use std::path::Path;

use crate::{Result, workspace_root};

const USAGE: &str = "usage: cargo xtask tables <name> [--check]

commands:
  units    regenerate crates/asrs-log/src/units/tables.rs from
           reference/AdvantageScope/src/shared/units.ts
  spark    regenerate crates/asrs-formats/src/spark/tables.rs from
           reference/AdvantageScope/src/hub/dataSources/schema/spark/spark-frames-{2025,2026}.ts";

const GENERATED: &str = "Generated by `cargo xtask tables units` from \
reference/AdvantageScope/src/shared/units.ts.\n\
// Do not edit.";

pub fn run(args: &[String]) -> Result {
    let root = workspace_root();
    let check = args.iter().any(|a| a == "--check");
    let names: Vec<&String> = args.iter().filter(|a| !a.starts_with("--")).collect();
    match names.as_slice() {
        [name] if name.as_str() == "units" => units(&root, check),
        [name] if name.as_str() == "spark" => spark(&root, check),
        _ => Err(USAGE.to_owned()),
    }
}

fn units(root: &Path, check: bool) -> Result {
    let source_path = root.join("reference/AdvantageScope/src/shared/units.ts");
    let source =
        fs::read_to_string(&source_path).map_err(|e| format!("{}: {e}", source_path.display()))?;
    let text = rustfmt(&generate(&source)?)?;
    let out = root.join("crates/asrs-log/src/units/tables.rs");
    if check {
        let committed = fs::read_to_string(&out).map_err(|e| format!("{}: {e}", out.display()))?;
        return if committed == text {
            eprintln!("{}: up to date", out.display());
            Ok(())
        } else {
            Err(format!(
                "{}: differs from what units.ts generates; run `cargo xtask tables units`",
                out.display()
            ))
        };
    }
    fs::create_dir_all(out.parent().expect("tables.rs has a parent"))
        .map_err(|e| format!("{}: {e}", out.display()))?;
    fs::write(&out, &text).map_err(|e| format!("{}: {e}", out.display()))?;
    eprintln!("{}: written", out.display());
    Ok(())
}

/// Formats generated code the way `cargo fmt --all --check` expects, so the
/// committed file compares equal before and after a workspace fmt pass.
fn rustfmt(text: &str) -> Result<String> {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .as_mut()
        .expect("piped stdin")
        .write_all(text.as_bytes())
        .map_err(|e| format!("rustfmt stdin: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    String::from_utf8(out.stdout).map_err(|e| format!("rustfmt output: {e}"))
}

enum Lit {
    Obj(Vec<(String, Lit)>),
    Arr(Vec<Lit>),
    Str(String),
    Raw(String),
}

struct Parser<'a> {
    text: &'a [u8],
    pos: usize,
}

impl<'a> Parser<'a> {
    fn at(&self, offset: usize) -> u8 {
        *self.text.get(self.pos + offset).unwrap_or(&0)
    }

    fn skip_trivia(&mut self) {
        loop {
            match (self.at(0), self.at(1)) {
                (b'/', b'/') => {
                    while self.pos < self.text.len() && self.at(0) != b'\n' {
                        self.pos += 1;
                    }
                }
                (b'/', b'*') => {
                    self.pos += 2;
                    while self.pos < self.text.len() && !(self.at(0) == b'*' && self.at(1) == b'/')
                    {
                        self.pos += 1;
                    }
                    self.pos = (self.pos + 2).min(self.text.len());
                }
                (c, _) if c.is_ascii_whitespace() => self.pos += 1,
                _ => return,
            }
        }
    }

    fn fail<T>(&self, what: &str) -> Result<T> {
        let line = self.text[..self.pos]
            .iter()
            .filter(|c| **c == b'\n')
            .count()
            + 1;
        Err(format!("units.ts:{line}: {what}"))
    }

    fn string(&mut self) -> Result<String> {
        let quote = self.at(0);
        debug_assert!(quote == b'"' || quote == b'\'');
        self.pos += 1;
        let mut out = String::new();
        loop {
            let c = self.at(0);
            if c == 0 {
                return self.fail("unterminated string");
            }
            self.pos += 1;
            match c {
                c if c == quote => return Ok(out),
                b'\\' => {
                    let esc = self.at(0);
                    self.pos += 1;
                    match esc {
                        b'u' => {
                            let hex = self
                                .text
                                .get(self.pos..self.pos + 4)
                                .ok_or_else(|| "bad \\u".to_owned())?;
                            let hex = std::str::from_utf8(hex).map_err(|e| e.to_string())?;
                            let cp = u32::from_str_radix(hex, 16)
                                .map_err(|e| format!("bad \\u{hex}: {e}"))?;
                            self.pos += 4;
                            match char::from_u32(cp) {
                                Some(c) => out.push(c),
                                None => return self.fail("lone surrogate escape"),
                            }
                        }
                        b'x' => {
                            let hex = self
                                .text
                                .get(self.pos..self.pos + 2)
                                .ok_or_else(|| "bad \\x".to_owned())?;
                            let hex = std::str::from_utf8(hex).map_err(|e| e.to_string())?;
                            let cp = u32::from_str_radix(hex, 16)
                                .map_err(|e| format!("bad \\x{hex}: {e}"))?;
                            self.pos += 2;
                            match char::from_u32(cp) {
                                Some(c) => out.push(c),
                                None => return self.fail("lone surrogate escape"),
                            }
                        }
                        b'n' => out.push('\n'),
                        b'r' => out.push('\r'),
                        b't' => out.push('\t'),
                        b'"' | b'\'' | b'\\' => out.push(esc as char),
                        _ => return self.fail("unsupported string escape"),
                    }
                }
                _ => {
                    let len = utf8_len(c);
                    out.push_str(
                        std::str::from_utf8(&self.text[self.pos - 1..self.pos - 1 + len])
                            .map_err(|e| e.to_string())?,
                    );
                    self.pos += len - 1;
                }
            }
        }
    }

    /// A run of expression characters up to `,` `}` `]` or a `//` comment.
    fn atom(&mut self) -> String {
        let start = self.pos;
        while self.pos < self.text.len() {
            let c = self.at(0);
            if c == b',' || c == b'}' || c == b']' {
                break;
            }
            if c == b'/' && self.at(1) == b'/' {
                break;
            }
            self.pos += 1;
        }
        String::from_utf8_lossy(&self.text[start..self.pos])
            .trim()
            .to_owned()
    }

    fn value(&mut self) -> Result<Lit> {
        self.skip_trivia();
        let value = match self.at(0) {
            b'{' => self.object(),
            b'[' => self.array(),
            b'"' | b'\'' => Ok(Lit::Str(self.string()?)),
            _ => Ok(Lit::Raw(self.atom())),
        };
        // `x as const` suffixes (the spark frame specs use them). Raw atoms already
        // consumed the suffix, so this only applies after structured/string values.
        let save = self.pos;
        self.skip_trivia();
        if self.text[self.pos..].starts_with(b"as const")
            && !self.at(8).is_ascii_alphanumeric()
            && self.at(8) != b'_'
        {
            self.pos += 8;
        } else {
            self.pos = save;
        }
        value
    }

    fn object(&mut self) -> Result<Lit> {
        self.pos += 1;
        let mut entries = Vec::new();
        loop {
            self.skip_trivia();
            match self.at(0) {
                b'}' => {
                    self.pos += 1;
                    return Ok(Lit::Obj(entries));
                }
                0 => return self.fail("unterminated object"),
                _ => {}
            }
            let key = if self.at(0) == b'"' || self.at(0) == b'\'' {
                self.string()?
            } else {
                let start = self.pos;
                while self.pos < self.text.len()
                    && (self.at(0).is_ascii_alphanumeric()
                        || self.at(0) == b'_'
                        || self.at(0) == b'$')
                {
                    self.pos += 1;
                }
                String::from_utf8_lossy(&self.text[start..self.pos]).into_owned()
            };
            self.skip_trivia();
            if self.at(0) != b':' {
                return self.fail(&format!("expected `:` after key {key:?}"));
            }
            if key.is_empty() {
                return self.fail("expected a property name");
            }
            if key.bytes().all(|b| b.is_ascii_digit()) {
                return self.fail(&format!("integer-like key {key:?} reorders in JS"));
            }
            if entries.iter().any(|(k, _)| *k == key) {
                return self.fail(&format!("duplicate key {key:?}"));
            }
            self.pos += 1;
            let value = self.value()?;
            entries.push((key, value));
            self.skip_trivia();
            match self.at(0) {
                b',' => self.pos += 1,
                b'}' => {
                    self.pos += 1;
                    return Ok(Lit::Obj(entries));
                }
                _ => {
                    let key = &entries.last().expect("parsed a pair").0;
                    return self.fail(&format!("expected `,` or `}}` after {key:?}"));
                }
            }
        }
    }

    fn array(&mut self) -> Result<Lit> {
        self.pos += 1;
        let mut items = Vec::new();
        loop {
            self.skip_trivia();
            match self.at(0) {
                b']' => {
                    self.pos += 1;
                    return Ok(Lit::Arr(items));
                }
                0 => return self.fail("unterminated array"),
                _ => {}
            }
            items.push(self.value()?);
            self.skip_trivia();
            match self.at(0) {
                b',' => self.pos += 1,
                b']' => {
                    self.pos += 1;
                    return Ok(Lit::Arr(items));
                }
                _ => return self.fail("expected `,` or `]`"),
            }
        }
    }
}

fn utf8_len(first: u8) -> usize {
    match first {
        0..=0x7f => 1,
        0xc0..=0xdf => 2,
        0xe0..=0xef => 3,
        _ => 4,
    }
}

/// The object literal assigned to `export const <name>` in the source.
fn named_object(source: &str, name: &str) -> Result<Lit> {
    let marker = format!("export const {name}");
    let start = source
        .find(&marker)
        .ok_or_else(|| format!("units.ts: no `{marker}`"))?;
    let equals = source[start..]
        .find('=')
        .ok_or_else(|| format!("units.ts: no `=` after {name}"))?
        + start;
    let brace = source[equals..]
        .find('{')
        .ok_or_else(|| format!("units.ts: no `{{` after {name}"))?
        + equals;
    let mut parser = Parser {
        text: source.as_bytes(),
        pos: brace,
    };
    parser.object()
}

fn str_value<'a>(lit: &'a Lit, what: &str) -> Result<&'a str> {
    match lit {
        Lit::Str(s) => Ok(s),
        _ => Err(format!("units.ts: {what} must be a string")),
    }
}

fn rust_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Translates a JS arithmetic expression into the identical Rust f64
/// expression. Only decimal literals, `+ - * / ( )` and `Math.PI` (same bits
/// as `f64::consts::PI`) are accepted; anything else fails, so the const keeps
/// V8's value and evaluation order.
fn rust_expr(expr: &str) -> Result<String> {
    let fail = || format!("units.ts: unsupported value expression {expr:?}");
    let mut out = String::new();
    let bytes = expr.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        if c.is_ascii_digit() {
            let start = i;
            while i < bytes.len() && bytes[i].is_ascii_digit() {
                i += 1;
            }
            let mut float = false;
            if bytes.get(i) == Some(&b'.') {
                float = true;
                i += 1;
                let digits = i;
                while i < bytes.len() && bytes[i].is_ascii_digit() {
                    i += 1;
                }
                if i == digits {
                    return Err(fail());
                }
            }
            if matches!(bytes.get(i), Some(b'e' | b'E')) {
                float = true;
                i += 1;
                if matches!(bytes.get(i), Some(b'+' | b'-')) {
                    i += 1;
                }
                let digits = i;
                while i < bytes.len() && bytes[i].is_ascii_digit() {
                    i += 1;
                }
                if i == digits {
                    return Err(fail());
                }
            }
            if bytes
                .get(i)
                .is_some_and(|b| b.is_ascii_alphanumeric() || *b == b'_' || *b == b'.')
            {
                return Err(fail());
            }
            out.push_str(&expr[start..i]);
            if !float {
                out.push_str(".0");
            }
        } else if expr[i..].starts_with("Math.PI")
            && !bytes
                .get(i + "Math.PI".len())
                .is_some_and(|b| b.is_ascii_alphanumeric() || *b == b'_' || *b == b'$')
        {
            out.push_str("std::f64::consts::PI");
            i += "Math.PI".len();
        } else if b"+-*/() ".contains(&c) {
            if c == b'*' && bytes.get(i + 1) == Some(&b'*') {
                return Err(fail());
            }
            out.push(c as char);
            i += 1;
        } else {
            return Err(fail());
        }
    }
    let trimmed = out.trim().to_owned();
    if trimmed.is_empty() {
        return Err(fail());
    }
    Ok(trimmed)
}

fn unit_config(props: &Lit, unit: &str) -> Result<String> {
    let Lit::Obj(entries) = props else {
        return Err(format!("units.ts: unit {unit:?} is not an object"));
    };
    if let Some((key, _)) = entries
        .iter()
        .find(|(k, _)| !["value", "suffix", "pluralizeSuffix", "names"].contains(&k.as_str()))
    {
        return Err(format!(
            "units.ts: unit {unit:?} has unknown property {key:?}"
        ));
    }
    let get = |key: &str| -> Result<&Lit> {
        entries
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v)
            .ok_or_else(|| format!("units.ts: unit {unit:?} has no {key:?}"))
    };
    let value = match get("value")? {
        Lit::Raw(expr) => rust_expr(expr)?,
        _ => {
            return Err(format!(
                "units.ts: unit {unit:?} value is not an expression"
            ));
        }
    };
    let suffix = rust_string(str_value(get("suffix")?, "suffix")?);
    let pluralize = match get("pluralizeSuffix")? {
        Lit::Raw(raw) => match raw.trim() {
            "true" => "true",
            "false" => "false",
            other => return Err(format!("units.ts: pluralizeSuffix {other:?}")),
        },
        _ => return Err(format!("units.ts: {unit:?} pluralizeSuffix is not a bool")),
    };
    let Lit::Arr(names) = get("names")? else {
        return Err(format!("units.ts: {unit:?} names is not an array"));
    };
    let mut names_text = String::new();
    for name in names {
        if !names_text.is_empty() {
            names_text.push_str(", ");
        }
        names_text.push_str(&rust_string(str_value(name, "name")?));
    }
    Ok(format!(
        "UnitConfig {{ value: {value}, suffix: {suffix}, pluralize_suffix: {pluralize}, names: &[{names_text}] }}"
    ))
}

fn generate(source: &str) -> Result<String> {
    let groups = named_object(source, "UNIT_GROUPS")?;
    let struct_units = named_object(source, "STRUCT_UNITS")?;
    let mut text = format!("// {GENERATED}\n\nuse super::UnitConfig;\n");
    let Lit::Obj(group_entries) = groups else {
        return Err("units.ts: UNIT_GROUPS is not an object".to_owned());
    };
    let mut unit_count = 0;
    text.push_str("\npub static UNIT_GROUPS: &[(&str, &[(&str, UnitConfig)])] = &[");
    for (group, units) in &group_entries {
        let Lit::Obj(unit_entries) = units else {
            return Err(format!("units.ts: group {group:?} is not an object"));
        };
        unit_count += unit_entries.len();
        text.push_str(&format!("\n    ({}, &[", rust_string(group)));
        for (unit, props) in unit_entries {
            text.push_str(&format!(
                "\n        ({}, {}),",
                rust_string(unit),
                unit_config(props, unit)?
            ));
        }
        text.push_str("\n    ]),");
    }
    text.push_str("\n];\n");
    let Lit::Obj(struct_entries) = struct_units else {
        return Err("units.ts: STRUCT_UNITS is not an object".to_owned());
    };
    text.push_str("\npub static STRUCT_UNITS: &[(&str, &[(&str, &str)])] = &[");
    for (ty, children) in &struct_entries {
        let Lit::Obj(child_entries) = children else {
            return Err(format!("units.ts: struct {ty:?} is not an object"));
        };
        text.push_str(&format!("\n    ({}, &[", rust_string(ty)));
        for (child, unit) in child_entries {
            text.push_str(&format!(
                "({}, {}),",
                rust_string(child),
                rust_string(str_value(unit, "struct unit")?)
            ));
        }
        text.push_str("]),");
    }
    text.push_str("\n];\n");
    eprintln!(
        "units.ts: {} groups, {} units, {} struct types",
        group_entries.len(),
        unit_count,
        struct_entries.len()
    );
    Ok(text)
}

const SPARK_GENERATED: &str = "Generated by `cargo xtask tables spark` from \
reference/AdvantageScope/src/hub/dataSources/schema/spark/spark-frames-{2025,2026}.ts.\n\
// Do not edit.";

/// The frames upstream `URCLSchema.ts` decodes, per spec file.
const SPARK_USED: &[(&str, &[&str], &[&str])] = &[
    (
        "2025",
        &[
            "STATUS_0", "STATUS_1", "STATUS_2", "STATUS_3", "STATUS_4", "STATUS_5", "STATUS_6",
            "STATUS_7",
        ],
        &[],
    ),
    (
        "2026",
        &[
            "STATUS_0", "STATUS_1", "STATUS_2", "STATUS_3", "STATUS_4", "STATUS_5", "STATUS_6",
            "STATUS_7",
        ],
        &["GET_FIRMWARE_VERSION"],
    ),
];

fn spark(root: &Path, check: bool) -> Result {
    let mut text =
        format!("// {SPARK_GENERATED}\n\nuse super::{{Frame, FrameKind, Signal, SignalType}};\n");
    let mut frames = 0;
    let mut signals = 0;
    for (year, periodic, non_periodic) in SPARK_USED {
        let source_path = root.join(format!(
            "reference/AdvantageScope/src/hub/dataSources/schema/spark/spark-frames-{year}.ts"
        ));
        let source = fs::read_to_string(&source_path)
            .map_err(|e| format!("{}: {e}", source_path.display()))?;
        let spec_lit = named_object(&source, "sparkFramesSpec")
            .map_err(|e| format!("spark-frames-{year}.ts: {e}"))?;
        let spec = spark_spec(&spec_lit, year)?;
        for frame_name in periodic.iter().chain(non_periodic.iter()) {
            let (frame, signal_count) = spark_frame(&spec, year, frame_name)?;
            frames += 1;
            signals += signal_count;
            text.push_str(&frame);
        }
        let status_list: Vec<String> = periodic.iter().map(|f| format!("&{f}_{year}")).collect();
        text.push_str(&format!(
            "\n/// `sparkFramesSpec{year}.periodicFrames` in spec order (the subset URCLSchema uses).\npub static STATUS_{year}: &[&Frame] = &[{}];\n",
            status_list.join(", ")
        ));
    }
    let text = rustfmt(&text)?;
    let out = root.join("crates/asrs-formats/src/spark/tables.rs");
    if check {
        let committed = fs::read_to_string(&out).map_err(|e| format!("{}: {e}", out.display()))?;
        return if committed == text {
            eprintln!("{}: up to date", out.display());
            Ok(())
        } else {
            Err(format!(
                "{}: differs from what spark-frames generates; run `cargo xtask tables spark`",
                out.display()
            ))
        };
    }
    fs::create_dir_all(out.parent().expect("tables.rs has a parent"))
        .map_err(|e| format!("{}: {e}", out.display()))?;
    fs::write(&out, &text).map_err(|e| format!("{}: {e}", out.display()))?;
    eprintln!(
        "{}: written ({frames} frames, {signals} signals)",
        out.display()
    );
    Ok(())
}

struct SparkSpec<'a> {
    periodic: &'a [(String, Lit)],
    non_periodic: &'a [(String, Lit)],
}

/// Parses `sparkFramesSpec` and validates every frame and signal in the file,
/// so upstream additions in a shape we do not handle fail here rather than
/// being silently dropped.
fn spark_spec<'a>(spec: &'a Lit, year: &str) -> Result<SparkSpec<'a>> {
    let ctx = || format!("spark-frames-{year}.ts");
    let Lit::Obj(entries) = spec else {
        return Err(format!("{}: sparkFramesSpec is not an object", ctx()));
    };
    for (key, _) in entries {
        if ![
            "frcJsonSpecVersion",
            "framesVersion",
            "deviceInfo",
            "periodicFrames",
            "nonPeriodicFrames",
        ]
        .contains(&key.as_str())
        {
            return Err(format!("{}: unexpected spec property {key:?}", ctx()));
        }
    }
    for key in ["frcJsonSpecVersion", "framesVersion"] {
        match spark_get(entries, key) {
            Some(Lit::Str(_)) => {}
            _ => return Err(format!("{}: {key} must be a string", ctx())),
        }
    }
    let Lit::Obj(device) = spark_need(entries, "deviceInfo", &ctx())? else {
        return Err(format!("{}: deviceInfo is not an object", ctx()));
    };
    for (key, value) in device {
        let ok = match key.as_str() {
            "deviceType" | "manufacturer" => matches!(value, Lit::Str(_)),
            "deviceTypeNumber" | "manufacturerNumber" => spark_uint(value).is_ok(),
            _ => return Err(format!("{}: unexpected deviceInfo property {key:?}", ctx())),
        };
        if !ok {
            return Err(format!(
                "{}: deviceInfo.{key} has an unexpected type",
                ctx()
            ));
        }
    }
    for key in [
        "deviceType",
        "deviceTypeNumber",
        "manufacturer",
        "manufacturerNumber",
    ] {
        spark_need(device, key, &ctx())?;
    }
    let periodic = spark_obj(spark_need(entries, "periodicFrames", &ctx())?, &ctx())?;
    let non_periodic = spark_obj(spark_need(entries, "nonPeriodicFrames", &ctx())?, &ctx())?;
    for (name, frame) in periodic {
        spark_frame_shape(frame, true, &format!("{}: periodic frame {name}", ctx()))?;
    }
    for (name, frame) in non_periodic {
        spark_frame_shape(frame, false, &format!("{}: frame {name}", ctx()))?;
    }
    Ok(SparkSpec {
        periodic,
        non_periodic,
    })
}

fn spark_get<'a>(entries: &'a [(String, Lit)], key: &str) -> Option<&'a Lit> {
    entries.iter().find(|(k, _)| k == key).map(|(_, v)| v)
}

fn spark_need<'a>(entries: &'a [(String, Lit)], key: &str, ctx: &str) -> Result<&'a Lit> {
    spark_get(entries, key).ok_or_else(|| format!("{ctx}: missing property {key:?}"))
}

fn spark_obj<'a>(lit: &'a Lit, ctx: &str) -> Result<&'a [(String, Lit)]> {
    match lit {
        Lit::Obj(entries) => Ok(entries),
        _ => Err(format!("{ctx}: expected an object")),
    }
}

fn spark_str<'a>(lit: &'a Lit, ctx: &str) -> Result<&'a str> {
    match lit {
        Lit::Str(s) => Ok(s),
        _ => Err(format!("{ctx}: expected a string")),
    }
}

/// The text of a `Lit::Raw` with an `as const` suffix removed.
fn spark_raw<'a>(lit: &'a Lit, ctx: &str) -> Result<&'a str> {
    match lit {
        Lit::Raw(s) => {
            let s = s.trim();
            Ok(s.strip_suffix("as const").unwrap_or(s).trim())
        }
        _ => Err(format!("{ctx}: expected a literal")),
    }
}

fn spark_uint(lit: &Lit) -> Result<u64> {
    let Lit::Raw(s) = lit else {
        return Err("expected an integer literal".to_owned());
    };
    let s = s.trim().strip_suffix("as const").unwrap_or(s.trim()).trim();
    if s.is_empty() || !s.bytes().all(|b| b.is_ascii_digit()) {
        return Err(format!("expected an integer literal, got {s:?}"));
    }
    s.parse().map_err(|e| format!("bad integer {s:?}: {e}"))
}

fn spark_bool(lit: &Lit, ctx: &str) -> Result<bool> {
    match spark_raw(lit, ctx)? {
        "true" => Ok(true),
        "false" => Ok(false),
        other => Err(format!("{ctx}: expected a boolean, got {other:?}")),
    }
}

/// `BigNumber("...")` -> the validated decimal literal.
fn spark_decimal(lit: &Lit, ctx: &str) -> Result<String> {
    let raw = spark_raw(lit, ctx)?;
    let inner = raw
        .strip_prefix("BigNumber(\"")
        .and_then(|s| s.strip_suffix("\")"))
        .ok_or_else(|| format!("{ctx}: expected BigNumber(\"...\"), got {raw:?}"))?;
    if !spark_is_numeric(inner) {
        return Err(format!("{ctx}: unsupported BigNumber literal {inner:?}"));
    }
    Ok(inner.to_owned())
}

/// The bignumber.js `isNumeric` grammar.
fn spark_is_numeric(s: &str) -> bool {
    let s = s.strip_prefix('-').unwrap_or(s);
    let (mantissa, exp) = match s.find(['e', 'E']) {
        Some(i) => (&s[..i], &s[i + 1..]),
        None => (s, ""),
    };
    if !exp.is_empty() {
        let digits = exp.strip_prefix(['+', '-']).unwrap_or(exp);
        if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
            return false;
        }
    } else if s.len() != mantissa.len() {
        return false;
    }
    let (int, frac) = match mantissa.split_once('.') {
        Some((i, f)) => (i, f),
        None => (mantissa, ""),
    };
    (!int.is_empty()
        && int.bytes().all(|b| b.is_ascii_digit())
        && frac.bytes().all(|b| b.is_ascii_digit()))
        || (int.is_empty() && !frac.is_empty() && frac.bytes().all(|b| b.is_ascii_digit()))
}

/// Validates a frame object literal against the upstream shape.
fn spark_frame_shape(frame: &Lit, periodic: bool, ctx: &str) -> Result {
    let entries = spark_obj(frame, ctx)?;
    for (key, _) in entries {
        let allowed = [
            "name",
            "description",
            "apiClass",
            "apiIndex",
            "arbId",
            "lengthBytes",
            "signals",
            "versionImplemented",
            "versionDeprecated",
            "versionRemoved",
            "broadcast",
            "defaultPeriodMs",
            "enabledByDefault",
            "rtr",
            "frameRangeName",
        ];
        if !allowed.contains(&key.as_str()) {
            return Err(format!("{ctx}: unexpected frame property {key:?}"));
        }
    }
    for key in [
        "name",
        "apiClass",
        "apiIndex",
        "arbId",
        "lengthBytes",
        "signals",
        "versionImplemented",
        "broadcast",
    ] {
        spark_need(entries, key, ctx)?;
    }
    spark_str(spark_get(entries, "name").expect("checked"), ctx)?;
    for key in ["apiClass", "apiIndex", "arbId", "lengthBytes"] {
        spark_uint(spark_get(entries, key).expect("checked"))
            .map_err(|e| format!("{ctx}: {key}: {e}"))?;
    }
    let length_bytes = spark_uint(spark_get(entries, "lengthBytes").expect("checked"))
        .map_err(|e| format!("{ctx}: lengthBytes: {e}"))?;
    if length_bytes > 8 {
        return Err(format!("{ctx}: lengthBytes {length_bytes} exceeds 8"));
    }
    spark_bool(spark_get(entries, "broadcast").expect("checked"), ctx)?;
    spark_str(
        spark_get(entries, "versionImplemented").expect("checked"),
        ctx,
    )?;
    for key in [
        "description",
        "versionDeprecated",
        "versionRemoved",
        "frameRangeName",
    ] {
        if let Some(v) = spark_get(entries, key) {
            spark_str(v, &format!("{ctx}: {key}"))?;
        }
    }
    if periodic {
        for key in ["rtr", "frameRangeName"] {
            if spark_get(entries, key).is_some() {
                return Err(format!("{ctx}: periodic frame has {key:?}"));
            }
        }
        spark_uint(spark_need(entries, "defaultPeriodMs", ctx)?)
            .map_err(|e| format!("{ctx}: defaultPeriodMs: {e}"))?;
        spark_bool(spark_need(entries, "enabledByDefault", ctx)?, ctx)?;
    } else {
        for key in ["defaultPeriodMs", "enabledByDefault"] {
            if spark_get(entries, key).is_some() {
                return Err(format!("{ctx}: non-periodic frame has {key:?}"));
            }
        }
        spark_bool(spark_need(entries, "rtr", ctx)?, ctx)?;
    }
    let signals = spark_obj(spark_get(entries, "signals").expect("checked"), ctx)?;
    for (key, signal) in signals {
        spark_signal_shape(signal, &format!("{ctx} signal {key}"))?;
    }
    Ok(())
}

fn spark_signal_shape(signal: &Lit, ctx: &str) -> Result {
    let entries = spark_obj(signal, ctx)?;
    for (key, _) in entries {
        let allowed = [
            "type",
            "name",
            "description",
            "bitPosition",
            "isBigEndian",
            "lengthBits",
            "decodeScaleFactor",
            "offset",
            "decodedMin",
            "decodedMax",
            "encodedMin",
            "encodedMax",
            "unit",
        ];
        if !allowed.contains(&key.as_str()) {
            return Err(format!("{ctx}: unexpected signal property {key:?}"));
        }
    }
    for key in [
        "type",
        "name",
        "bitPosition",
        "isBigEndian",
        "lengthBits",
        "decodeScaleFactor",
        "offset",
    ] {
        spark_need(entries, key, ctx)?;
    }
    let ty = spark_str(spark_get(entries, "type").expect("checked"), ctx)?;
    if !["boolean", "uint", "int", "float", "double"].contains(&ty) {
        return Err(format!("{ctx}: unknown signal type {ty:?}"));
    }
    spark_str(spark_get(entries, "name").expect("checked"), ctx)?;
    let bit_position = spark_uint(spark_get(entries, "bitPosition").expect("checked"))
        .map_err(|e| format!("{ctx}: bitPosition: {e}"))?;
    let length_bits = spark_uint(spark_get(entries, "lengthBits").expect("checked"))
        .map_err(|e| format!("{ctx}: lengthBits: {e}"))?;
    if length_bits == 0 || bit_position + length_bits > 64 {
        return Err(format!(
            "{ctx}: bits {bit_position}..{length_bits} outside the 64-bit payload"
        ));
    }
    spark_bool(spark_get(entries, "isBigEndian").expect("checked"), ctx)?;
    spark_decimal(
        spark_get(entries, "decodeScaleFactor").expect("checked"),
        ctx,
    )?;
    spark_decimal(spark_get(entries, "offset").expect("checked"), ctx)?;
    for key in ["decodedMin", "decodedMax", "encodedMin", "encodedMax"] {
        if let Some(v) = spark_get(entries, key) {
            spark_decimal(v, &format!("{ctx}: {key}"))?;
        }
    }
    for key in ["description", "unit"] {
        if let Some(v) = spark_get(entries, key) {
            spark_str(v, &format!("{ctx}: {key}"))?;
        }
    }
    let encoded = ["encodedMin", "encodedMax"];
    if matches!(ty, "float" | "double") {
        for key in encoded {
            if spark_get(entries, key).is_some() {
                return Err(format!("{ctx}: {ty} signal has {key:?}"));
            }
        }
    } else {
        for key in encoded {
            spark_need(entries, key, ctx)?;
        }
    }
    Ok(())
}

/// Emits the `static` for one validated frame; returns the text and its signal count.
fn spark_frame(spec: &SparkSpec<'_>, year: &str, frame_name: &str) -> Result<(String, usize)> {
    let ctx = format!("spark-frames-{year}.ts: {frame_name}");
    let found = spec
        .periodic
        .iter()
        .find(|(k, _)| k == frame_name)
        .map(|(_, f)| (true, f))
        .or_else(|| {
            spec.non_periodic
                .iter()
                .find(|(k, _)| k == frame_name)
                .map(|(_, f)| (false, f))
        });
    let Some((is_periodic, frame)) = found else {
        return Err(format!("{ctx}: frame not present in spec"));
    };
    let entries = spark_obj(frame, &ctx)?;
    let signals = spark_obj(spark_get(entries, "signals").expect("validated"), &ctx)?;
    let mut body = String::new();
    for (key, signal) in signals {
        if key
            .parse::<u32>()
            .is_ok_and(|n| n.to_string() == *key && n != u32::MAX)
        {
            return Err(format!(
                "{ctx}: signal key {key:?} is an array index, which reorders Object.keys"
            ));
        }
        let e = spark_obj(signal, &ctx)?;
        let ty = spark_str(spark_get(e, "type").expect("validated"), &ctx)?;
        let rust_ty = match ty {
            "boolean" => "SignalType::Boolean",
            "uint" => "SignalType::Uint",
            "int" => "SignalType::Int",
            "float" => "SignalType::Float",
            // Upstream decodes doubles through `writeBigUInt64LE(Number(uint))`, which
            // always throws, so a used frame with one needs that throw ported first.
            "double" => {
                return Err(format!(
                    "{ctx}: signal {key}: double signals are not supported"
                ));
            }
            _ => unreachable!("validated"),
        };
        let opt_str = |key: &str| -> String {
            spark_get(e, key)
                .map(|v| {
                    format!(
                        "Some({})",
                        rust_string(spark_str(v, &ctx).expect("validated"))
                    )
                })
                .unwrap_or_else(|| "None".to_owned())
        };
        let opt_dec = |key: &str| -> String {
            spark_get(e, key)
                .map(|v| {
                    format!(
                        "Some({})",
                        rust_string(&spark_decimal(v, &ctx).expect("validated"))
                    )
                })
                .unwrap_or_else(|| "None".to_owned())
        };
        body.push_str(&format!(
            "            ({}, Signal {{ signal_type: {rust_ty}, name: {}, bit_position: {}, length_bits: {}, is_big_endian: {}, description: {}, unit: {}, decode_scale_factor: {}, offset: {}, decoded_min: {}, decoded_max: {}, encoded_min: {}, encoded_max: {} }}),\n",
            rust_string(key),
            rust_string(spark_str(spark_get(e, "name").expect("validated"), &ctx)?),
            spark_uint(spark_get(e, "bitPosition").expect("validated"))
                .map_err(|e2| format!("{ctx}: bitPosition: {e2}"))?,
            spark_uint(spark_get(e, "lengthBits").expect("validated"))
                .map_err(|e2| format!("{ctx}: lengthBits: {e2}"))?,
            spark_bool(spark_get(e, "isBigEndian").expect("validated"), &ctx)?,
            opt_str("description"),
            opt_str("unit"),
            rust_string(&spark_decimal(spark_get(e, "decodeScaleFactor").expect("validated"), &ctx)?),
            rust_string(&spark_decimal(spark_get(e, "offset").expect("validated"), &ctx)?),
            opt_dec("decodedMin"),
            opt_dec("decodedMax"),
            opt_dec("encodedMin"),
            opt_dec("encodedMax"),
        ));
    }
    let opt_frame_str = |key: &str| -> String {
        spark_get(entries, key)
            .map(|v| {
                format!(
                    "Some({})",
                    rust_string(spark_str(v, &ctx).expect("validated"))
                )
            })
            .unwrap_or_else(|| "None".to_owned())
    };
    let kind = if is_periodic {
        format!(
            "FrameKind::Periodic {{ default_period_ms: {}, enabled_by_default: {} }}",
            spark_uint(spark_get(entries, "defaultPeriodMs").expect("validated"))
                .map_err(|e| format!("{ctx}: defaultPeriodMs: {e}"))?,
            spark_bool(
                spark_get(entries, "enabledByDefault").expect("validated"),
                &ctx
            )?,
        )
    } else {
        format!(
            "FrameKind::NonPeriodic {{ rtr: {} }}",
            spark_bool(spark_get(entries, "rtr").expect("validated"), &ctx)?,
        )
    };
    let name = format!("{frame_name}_{year}");
    let text = format!(
        "\npub static {name}: Frame = Frame {{\n    name: {},\n    description: {},\n    api_class: {},\n    api_index: {},\n    arb_id: {},\n    length_bytes: {},\n    signals: &[\n{body}    ],\n    broadcast: {},\n    version_implemented: {},\n    version_deprecated: {},\n    version_removed: {},\n    frame_range_name: {},\n    kind: {kind},\n}};\n",
        rust_string(spark_str(
            spark_get(entries, "name").expect("validated"),
            &ctx
        )?),
        opt_frame_str("description"),
        spark_uint(spark_get(entries, "apiClass").expect("validated"))
            .map_err(|e| format!("{ctx}: apiClass: {e}"))?,
        spark_uint(spark_get(entries, "apiIndex").expect("validated"))
            .map_err(|e| format!("{ctx}: apiIndex: {e}"))?,
        spark_uint(spark_get(entries, "arbId").expect("validated"))
            .map_err(|e| format!("{ctx}: arbId: {e}"))?,
        spark_uint(spark_get(entries, "lengthBytes").expect("validated"))
            .map_err(|e| format!("{ctx}: lengthBytes: {e}"))?,
        spark_bool(spark_get(entries, "broadcast").expect("validated"), &ctx)?,
        rust_string(spark_str(
            spark_get(entries, "versionImplemented").expect("validated"),
            &ctx
        )?),
        opt_frame_str("versionDeprecated"),
        opt_frame_str("versionRemoved"),
        opt_frame_str("frameRangeName"),
    );
    Ok((text, signals.len()))
}

#[cfg(test)]
mod tests {
    use super::generate;

    fn source(unit: &str) -> String {
        format!(
            "export const UNIT_GROUPS: {{ [id: string]: X }} = {{ g: {{ {unit} }} }};\n\
             export const STRUCT_UNITS: {{}} = {{ T: {{ a: \"u\" }} }};"
        )
    }

    fn unit(value: &str) -> String {
        format!("u: {{ value: {value}, suffix: \"s\", pluralizeSuffix: false, names: [\"u\"] }}")
    }

    #[test]
    fn accepts_upstream_shapes() {
        let text = generate(&source(&unit("1 / (Math.PI * 2)"))).unwrap();
        assert!(text.contains("value: 1.0 / (std::f64::consts::PI * 2.0)"));
        assert!(
            generate(&source(&unit("1e-3")))
                .unwrap()
                .contains("value: 1e-3,")
        );
    }

    #[test]
    fn rejects_unsupported_expressions() {
        for value in [
            "Math.sqrt(2)",
            "1_000",
            "0x10",
            ".5",
            "2 ** 3",
            "Math.PIE",
            "FACTOR",
            "1.",
        ] {
            assert!(generate(&source(&unit(value))).is_err(), "{value}");
        }
    }

    #[test]
    fn rejects_unexpected_object_shapes() {
        for units in [
            format!("{}, {}", unit("1"), unit("2")),
            format!("...OTHER, {}", unit("1")),
            format!("0: {{}}, {}", unit("1")),
            "u: { value: 1, suffix: \"s\", pluralizeSuffix: false, names: [\"u\"], offset: 3 }"
                .to_owned(),
            "u: { value: 1, suffix: `s`, pluralizeSuffix: false, names: [\"u\"] }".to_owned(),
            "u: { value: 1, suffix: \"\\a\", pluralizeSuffix: false, names: [\"u\"] }".to_owned(),
        ] {
            assert!(generate(&source(&units)).is_err(), "{units}");
        }
    }
}
